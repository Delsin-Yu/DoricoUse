using System.Text;
using System.Text.Json.Nodes;

namespace DoricoUse.Cli.Dorico;

/// <summary>
/// Reads the players of the document Dorico has open, without saving it.
/// </summary>
/// <remarks>
/// <para>
/// This exists because the Remote Control API cannot answer the question. Measured: the request table in the
/// application has no players request, and <c>getflows</c> — the request this was expected to come from — answers
/// a flow id and a flow name per flow and nothing else, on a one-player fixture and on a 38-player project alike.
/// The scripting layer, which <see cref="LiveRead"/> already uses for the same reason, does expose
/// <c>score.players</c>.
/// </para>
/// <para>
/// Every member the script asks a player for is wrapped in <c>pcall</c>, and a member the layer refuses is reported
/// as <c>unavailable</c> on that player rather than left looking like a null. That is the same shape as
/// <see cref="LiveRead"/>'s <c>unparsedLines</c>: the measure of what the layer gives is the report, not the claim.
/// </para>
/// </remarks>
internal static class LivePlayers
{
    /// <summary>How long the player read's own wait for the script's output file is, at least.</summary>
    public static readonly TimeSpan DefaultWait = LiveScript.DefaultWait;

    /// <summary>Where the script writes: a per-user file under the system temporary directory.</summary>
    public static string OutputPath { get; } = Path.Combine(LiveScript.Folder, "live-players.tsv");

    /// <summary>Where the generated script is written before Dorico is asked to run it.</summary>
    public static string ScriptPath { get; } = Path.Combine(LiveScript.Folder, "live-players.lua");

    /// <summary>
    /// The Lua the CLI asks Dorico to run. Generated rather than shipped as a file because Dorico's
    /// <c>Script.RunScript</c> takes no arguments, so the output path has to be written into the text.
    /// </summary>
    /// <param name="output">Where the script writes its dump. Must not contain the long-bracket terminator.</param>
    public static string Script(string output)
    {
        if (output.Contains("]]", StringComparison.Ordinal))
        {
            throw new CliException("InvalidArgument", "The output path may not contain ']]'.", 1);
        }

        var text = new StringBuilder();

        text.AppendLine("-- Generated by dorico-use: list the players of the open document, and nothing else.");
        text.AppendLine("-- Read-only by construction. Every member read is inside pcall so a member this layer does");
        text.AppendLine("-- not implement is reported as a failure instead of taking the whole read down.");
        text.AppendLine("local out = io.open([[" + output + "]], 'w')");
        text.AppendLine("if out == nil then return end");
        text.AppendLine("local function w(...)");
        text.AppendLine("  local parts = {}");
        text.AppendLine("  for index = 1, select('#', ...) do parts[#parts + 1] = tostring((select(index, ...))) end");
        text.AppendLine("  out:write(table.concat(parts, '\\t'), '\\n')");
        text.AppendLine("  out:flush()");
        text.AppendLine("end");
        text.AppendLine("w('" + LivePlayersDump.Header + "', '1')");
        text.AppendLine("local ok, app = pcall(function() return DoApp.DoApp() end)");
        text.AppendLine("if not ok then w('error', tostring(app)) out:close() return end");
        text.AppendLine("local score = app.currentScore");
        text.AppendLine("w('score', tostring(score.openScoreID), tostring(app.versionString))");
        text.AppendLine("local players = score.players");
        text.AppendLine("w('count', tostring(#players))");
        text.AppendLine("for pi = 1, #players do");
        text.AppendLine("  local player = players[pi]");
        text.AppendLine("  w('player', pi, tostring(player))");
        text.AppendLine("  local function ask(key, read)");
        text.AppendLine("    local sok, value = pcall(read)");
        text.AppendLine("    if sok and value ~= nil then");
        text.AppendLine("      w('member', pi, key, tostring(value))");
        text.AppendLine("    else");
        text.AppendLine("      w('memberfail', pi, key, sok and 'nil' or tostring(value))");
        text.AppendLine("    end");
        text.AppendLine("  end");
        text.AppendLine("  ask('id', function() return player.id end)");
        text.AppendLine("  ask('name', function() return player.name end)");
        text.AppendLine("  ask('shortName', function() return player.shortName end)");
        text.AppendLine("  ask('playerID', function() return player.playerID end)");
        text.AppendLine("  ask('soloPlayer', function() return player.soloPlayer end)");
        text.AppendLine("  ask('isSoloist', function() return player.isSoloist end)");
        text.AppendLine("  ask('instruments', function() return #player.instruments end)");
        text.AppendLine("end");
        text.AppendLine("out:close()");

        return text.ToString();
    }

    /// <summary>
    /// Writes the script, asks Dorico to run it and reads what it wrote. Nothing is saved and no document is
    /// rebound; the proof is the file, because <c>kOK</c> is only a receipt.
    /// </summary>
    /// <param name="timeout">How long Dorico has to run it and how long its output is then watched for.</param>
    /// <param name="cancellationToken">Cancellation.</param>
    /// <param name="expectScore">
    /// The document guard, when the caller knows which document it means: the script reads whichever document is
    /// active, so the host refuses the wrong one with <c>WrongActiveScore</c>. Null sends no guard.
    /// </param>
    public static async Task<JsonObject> RunAsync(
        TimeSpan timeout,
        CancellationToken cancellationToken,
        int? expectScore = null)
    {
        await LiveScript.WriteAsync(ScriptPath, Script(OutputPath), cancellationToken).ConfigureAwait(false);

        var (lines, dialog, acknowledgement) = await LiveScript
            .RunAsync(ScriptPath, OutputPath, timeout, expectScore, "players", cancellationToken)
            .ConfigureAwait(false);

        LiveScript.Forget(ScriptPath);

        var payload = LivePlayersDump.Parse(lines);

        payload["dialogWhileWaiting"] = dialog;
        payload["script"] = LiveScript.Report(acknowledgement);

        return payload;
    }
}
