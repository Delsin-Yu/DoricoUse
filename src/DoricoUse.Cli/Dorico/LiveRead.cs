using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;

namespace DoricoUse.Cli.Dorico;

/// <summary>
/// Reads the document Dorico has open, without saving it.
/// </summary>
/// <remarks>
/// <para>
/// <c>File.SaveAs</c> — the other way to see what a live document holds — rebinds that document to the copy it
/// writes, which is a dangerous thing for a read to do. This path instead asks Dorico to run a small Lua script
/// (see <see cref="Script"/>) that walks <c>score.flows → voiceStreams → dump()</c> and writes what it finds to a
/// file. Nothing is saved, nothing is rebound, and the document is untouched; the wording of the payload and the
/// caveats it carries come from <see cref="LiveReadDump"/>, which is what turns that text into JSON.
/// </para>
/// <para>
/// This is the read both <c>session read</c> and <c>note insert --read</c> do by default, in one invocation and
/// without a save; asking for <c>--rebind</c> (or <c>note insert --read-rebind</c>) is how a caller opts into
/// <see cref="SaveCopy"/> and the exact data instead.
/// </para>
/// <para>
/// The scripting layer can crash Dorico when it is probed blindly (see <c>docs/scripting.md</c> §8). The script
/// here calls five things only — <c>DoApp.DoApp</c>, <c>currentScore</c>, <c>flows</c>, <c>voiceStreams</c> and
/// <c>dump</c> — and every one of them was exercised before it was shipped.
/// </para>
/// </remarks>
internal sealed class LiveRead
{
    /// <summary>How long the output file is allowed to take, after the script answers.</summary>
    public static readonly TimeSpan DefaultWait = TimeSpan.FromSeconds(20);

    /// <summary>Where the script writes: a per-user file under the system temporary directory.</summary>
    public static string OutputPath { get; } = Path.Combine(Path.GetTempPath(), "dorico-use", "live-read.tsv");

    /// <summary>Where the generated script is written before Dorico is asked to run it.</summary>
    public static string ScriptPath { get; } = Path.Combine(Path.GetTempPath(), "dorico-use", "live-read.lua");

    /// <summary>
    /// The Lua the CLI asks Dorico to run. Generated rather than shipped as a file because Dorico's
    /// <c>Script.RunScript</c> takes no arguments, so the output path and the note limit have to be written into
    /// the text; and generated here rather than taken from anywhere else because it is Lua running inside the
    /// user's application with full file access.
    /// </summary>
    /// <param name="output">Where the script writes its dump. Must not contain the long-bracket terminator.</param>
    /// <param name="noteLimit">How many notes to write. Zero or less means every note in every stream.</param>
    public static string Script(string output, int noteLimit)
    {
        if (output.Contains("]]", StringComparison.Ordinal))
        {
            throw new CliException("InvalidArgument", "The output path may not contain ']]'.", 1);
        }

        var limit = noteLimit <= 0 ? "nil" : noteLimit.ToString(CultureInfo.InvariantCulture);
        var text = new StringBuilder();

        text.AppendLine("-- Generated by dorico-use: read the open document and write what is in it to a file.");
        text.AppendLine("-- Read-only by construction: five calls, all of them exercised before this shipped.");
        text.AppendLine("local out = io.open([[" + output + "]], 'w')");
        text.AppendLine("if out == nil then return end");
        text.AppendLine("local function w(...)");
        text.AppendLine("  local parts = {}");
        text.AppendLine("  for index = 1, select('#', ...) do parts[#parts + 1] = tostring((select(index, ...))) end");
        text.AppendLine("  out:write(table.concat(parts, '\\t'), '\\n')");
        text.AppendLine("  out:flush()");
        text.AppendLine("end");
        text.AppendLine("w('" + LiveReadDump.Header + "', '2')");
        text.AppendLine("local ok, app = pcall(function() return DoApp.DoApp() end)");
        text.AppendLine("if not ok then w('error', tostring(app)) out:close() return end");
        text.AppendLine("local score = app.currentScore");
        text.AppendLine("w('score', tostring(score.openScoreID), app.versionString)");
        text.AppendLine("local flows = score.flows");
        text.AppendLine("local wanted = " + limit);
        text.AppendLine("local written = 0");
        text.AppendLine("for fi = 1, #flows do");
        text.AppendLine("  local streams = flows[fi].voiceStreams");
        text.AppendLine("  for si = 1, #streams do");
        text.AppendLine("    local stream = streams[si]");
        text.AppendLine("    local ok2, message = pcall(function() return stream:dump() end)");
        text.AppendLine("    if not ok2 then");
        text.AppendLine("      w('stream', fi, stream.id, '-1', 'dump failed: ' .. tostring(message))");
        text.AppendLine("    else");
        text.AppendLine("      local kinds = {}");
        text.AppendLine("      local noteLines = {}");
        text.AppendLine("      for line in string.gmatch(message, '[^\\n]+') do");
        text.AppendLine("        local kind = string.match(line, '(k[A-Za-z]+Event)')");
        text.AppendLine("        if kind then kinds[kind] = (kinds[kind] or 0) + 1 end");
        text.AppendLine("        if kind == 'kNoteEvent' then noteLines[#noteLines + 1] = line end");
        text.AppendLine("      end");
        text.AppendLine("      local summary = {}");
        text.AppendLine("      local total = 0");
        text.AppendLine("      for kind, count in pairs(kinds) do");
        text.AppendLine("        summary[#summary + 1] = kind .. '=' .. count");
        text.AppendLine("        total = total + count");
        text.AppendLine("      end");
        text.AppendLine("      table.sort(summary)");
        text.AppendLine("      w('stream', fi, stream.id, total, table.concat(summary, ' '))");
        text.AppendLine("      for _, line in ipairs(noteLines) do");
        text.AppendLine("        if wanted ~= nil and written >= wanted then break end");
        text.AppendLine("        local id = string.match(line, '%(id:(%-?%d+)%)') or '-1'");
        text.AppendLine("        local position = string.match(line, 'at ([^ ]+)')");
        text.AppendLine("        local duration = string.match(line, 'duration ([^ ]+)')");
        text.AppendLine("        local pitch = string.match(line, '([A-G][#bx]*%d+) %(ends')");
        text.AppendLine("        if position and duration and pitch then");
        text.AppendLine("          w('note', fi, stream.id, id, position, duration, pitch, line)");
        text.AppendLine("          written = written + 1");
        text.AppendLine("        else");
        text.AppendLine("          w('unparsed', fi, stream.id, line)");
        text.AppendLine("        end");
        text.AppendLine("      end");
        text.AppendLine("    end");
        text.AppendLine("  end");
        text.AppendLine("end");
        text.AppendLine("w('notes', written)");
        text.AppendLine("out:close()");

        return text.ToString();
    }

    /// <summary>
    /// Writes the script, asks Dorico to run it, and reads what it wrote. Nothing outlives the invocation: the
    /// script is deleted afterwards, and the only thing it ever did was write a file.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The ack proves nothing — Dorico answers <c>kOK</c> to a <c>RunScript</c> that dies on its first line, and
    /// with <c>ShowConsole=false</c> there is nowhere for a Lua error to go — and it answers <c>kOK</c> just as
    /// readily when something modal is holding its command queue, in which case the script runs minutes later. The
    /// proof is the file, so this waits for it, and says exactly that when it never appears.
    /// </para>
    /// <para>
    /// This is what both <c>session read</c> and <c>note insert --read</c> run by default; the <c>--rebind</c> form
    /// of either reads a saved copy instead (<see cref="SaveCopy"/>).
    /// </para>
    /// </remarks>
    /// <param name="timeout">
    /// How long Dorico has to run the script and how long its output file is then watched for, so it has to cover
    /// both.
    /// </param>
    /// <param name="noteLimit">How many notes to write. Zero or less means every note in every stream.</param>
    /// <param name="cancellationToken">Cancellation.</param>
    /// <param name="expectScore">
    /// The document guard, when the caller knows which document it means: the script reads whichever document is
    /// active, so the host is handed this with the <c>Script.RunScript</c> request and refuses the wrong one
    /// (<c>WrongActiveScore</c>). Null sends no guard, which is what a caller with no document in mind wants.
    /// </param>
    public static async Task<JsonObject> RunAsync(
        TimeSpan timeout,
        int noteLimit,
        CancellationToken cancellationToken,
        int? expectScore = null)
    {
        var folder = Path.GetDirectoryName(OutputPath);

        if (string.IsNullOrEmpty(folder))
        {
            throw new CliException("RuntimeError", "The temporary folder could not be determined.", 2);
        }

        Directory.CreateDirectory(folder);
        File.Delete(OutputPath);
        await File.WriteAllTextAsync(ScriptPath, Script(OutputPath, noteLimit), new UTF8Encoding(false), cancellationToken)
            .ConfigureAwait(false);

        var acknowledgement = await SaveCopy
            .SendCommandAsync(
                "Script.RunScript",
                [
                    new("ScriptPath", ScriptPath.Replace('\\', '/')),
                    new("ShowConsole", "false"),
                ],
                timeout,
                cancellationToken,
                expectScore)
            .ConfigureAwait(false);

        var lines = await WaitForDumpAsync(timeout, cancellationToken).ConfigureAwait(false);

        try
        {
            File.Delete(ScriptPath);
        }
        catch (IOException)
        {
            // A leftover script in the temporary folder is harmless.
        }

        var payload = LiveReadDump.Parse(lines, noteLimit);

        payload["script"] = new JsonObject
        {
            ["command"] = "Script.RunScript",
            ["ack"] = NodeRead.Str(acknowledgement, "ack") ?? "unknown",
            ["note"] = "kOK is a receipt: with ShowConsole=false a script that fails leaves no trace, and a modal "
                + "dialog elsewhere in Dorico means the command is queued rather than run. The proof is the file this "
                + "read parsed, not the acknowledgement.",
        };

        return payload;
    }

    private static async Task<string[]> WaitForDumpAsync(TimeSpan timeout, CancellationToken cancellationToken)
    {
        var deadline = DateTimeOffset.UtcNow + timeout;
        var quiet = 0;
        long previous = -1;

        while (DateTimeOffset.UtcNow < deadline)
        {
            await Task.Delay(100, cancellationToken).ConfigureAwait(false);

            if (!File.Exists(OutputPath))
            {
                continue;
            }

            var size = new FileInfo(OutputPath).Length;

            if (size == previous && size > 0)
            {
                if (++quiet >= 2)
                {
                    try
                    {
                        return await File.ReadAllLinesAsync(OutputPath, cancellationToken).ConfigureAwait(false);
                    }
                    catch (IOException ex)
                    {
                        throw new CliException("LiveReadFailed", $"The script's output could not be read: {ex.Message}", 2);
                    }
                }

                continue;
            }

            quiet = 0;
            previous = size;
        }

        throw new CliException(
            "LiveReadWroteNothing",
            $"The read script produced no output at '{OutputPath}' within {timeout.TotalSeconds:0.#} s. Dorico "
            + "answers kOK to Script.RunScript whether the script runs, dies or sits behind a dialog, and with "
            + "ShowConsole=false a Lua error has nowhere to go, so this is all that can be reported. Check that a "
            + "document with at least one player is open (`session status`), that nothing modal is holding Dorico's "
            + "command queue (see %APPDATA%\\Steinberg\\Dorico 6\\application.log), and see docs/scripting.md before "
            + "probing the scripting layer further.",
            2);
    }
}
